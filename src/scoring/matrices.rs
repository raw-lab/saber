//! Protein substitution matrices (BLOSUM and PAM families) plus the
//! statistical parameters required for Karlin-Altschul E-value calculation.
//!
//! The lambda and K values bundled with each matrix come from the published
//! NCBI tables (see, e.g., the ungapped values used by `blastp`). They are
//! exposed via `karlin_altschul_params()` so the e-value module can compute
//! statistically meaningful scores instead of the placeholder defaults that
//! shipped in v2.0.

use std::fmt;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum ScoringSystem {
    Blosum45,
    Blosum50,
    Blosum62,
    Blosum80,
    Blosum90,
    Pam30,
    Pam70,
    Pam250,
}

impl fmt::Display for ScoringSystem {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Blosum45 => write!(f, "BLOSUM45"),
            Self::Blosum50 => write!(f, "BLOSUM50"),
            Self::Blosum62 => write!(f, "BLOSUM62"),
            Self::Blosum80 => write!(f, "BLOSUM80"),
            Self::Blosum90 => write!(f, "BLOSUM90"),
            Self::Pam30 => write!(f, "PAM30"),
            Self::Pam70 => write!(f, "PAM70"),
            Self::Pam250 => write!(f, "PAM250"),
        }
    }
}

impl std::str::FromStr for ScoringSystem {
    type Err = String;

    fn from_str(s: &str) -> Result<Self, Self::Err> {
        match s.to_uppercase().replace('_', "").as_str() {
            "BLOSUM45" => Ok(Self::Blosum45),
            "BLOSUM50" => Ok(Self::Blosum50),
            "BLOSUM62" => Ok(Self::Blosum62),
            "BLOSUM80" => Ok(Self::Blosum80),
            "BLOSUM90" => Ok(Self::Blosum90),
            "PAM30" => Ok(Self::Pam30),
            "PAM70" => Ok(Self::Pam70),
            "PAM250" => Ok(Self::Pam250),
            other => Err(format!("Unknown scoring matrix: {}", other)),
        }
    }
}

/// A loaded substitution matrix with O(1) score lookup.
pub struct ScoreMatrix {
    /// 24x24 matrix indexed by `char_to_idx`.
    pub matrix: [[i32; 24]; 24],
    pub system: ScoringSystem,
    /// Maps any ASCII byte to a column/row index. Unknowns route to `X` (idx 22).
    pub char_to_idx: [usize; 256],
}

impl ScoreMatrix {
    pub fn new(system: ScoringSystem) -> Self {
        let matrix = match system {
            ScoringSystem::Blosum45 => BLOSUM45_MATRIX,
            ScoringSystem::Blosum50 => BLOSUM50_MATRIX,
            ScoringSystem::Blosum62 => BLOSUM62_MATRIX,
            ScoringSystem::Blosum80 => BLOSUM80_MATRIX,
            ScoringSystem::Blosum90 => BLOSUM90_MATRIX,
            ScoringSystem::Pam30 => PAM30_MATRIX,
            ScoringSystem::Pam70 => PAM70_MATRIX,
            ScoringSystem::Pam250 => PAM250_MATRIX,
        };
        Self { matrix, system, char_to_idx: BLOSUM_CHAR_MAP }
    }

    /// Score one amino acid pair. Case-insensitive; unknown letters map to `X`.
    #[inline]
    pub fn score(&self, a1: u8, a2: u8) -> i32 {
        let i = self.char_to_idx[a1 as usize];
        let j = self.char_to_idx[a2 as usize];
        self.matrix[i][j]
    }

    /// Score by numeric alphabet index (0..23), used by the GPU encoding layer.
    /// Indices outside the alphabet are clamped to X (22).
    #[inline]
    pub fn score_by_index(&self, i: usize, j: usize) -> i32 {
        let i = i.min(23);
        let j = j.min(23);
        self.matrix[i][j]
    }

    /// Karlin-Altschul parameters (λ, K, H) for ungapped statistics on this matrix.
    /// Used by the E-value calculator. Values from NCBI's published tables.
    pub fn karlin_altschul_params(&self) -> (f64, f64, f64) {
        // (lambda, K, H) — ungapped, scale-1 alphabet
        match self.system {
            ScoringSystem::Blosum45 => (0.2291, 0.0924, 0.2287),
            ScoringSystem::Blosum50 => (0.2318, 0.112, 0.34),
            ScoringSystem::Blosum62 => (0.3176, 0.134, 0.4012),
            ScoringSystem::Blosum80 => (0.3434, 0.177, 0.6568),
            ScoringSystem::Blosum90 => (0.3346, 0.190, 0.7547),
            ScoringSystem::Pam30   => (0.3400, 0.283, 1.754),
            ScoringSystem::Pam70   => (0.3345, 0.229, 1.029),
            ScoringSystem::Pam250  => (0.2290, 0.0924, 0.230),
        }
    }
}

/// Index layout: A R N D C Q E G H I L K M F P S T W Y V B Z X *
const BLOSUM_CHAR_MAP: [usize; 256] = build_char_map();

const fn build_char_map() -> [usize; 256] {
    let mut m = [22usize; 256]; // default → X
    // Set both cases
    let chars = b"ARNDCQEGHILKMFPSTWYVBZX*";
    let mut i = 0;
    while i < chars.len() {
        m[chars[i] as usize] = i;
        // lowercase
        let lc = chars[i] + 32;
        m[lc as usize] = i;
        i += 1;
    }
    m
}

