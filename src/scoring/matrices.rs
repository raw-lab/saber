#[cfg(test)]
mod tests {
    use super::*;
    use std::str::FromStr;

    #[test]
    fn parse_scoring_system_handles_underscored_and_compact() {
        assert_eq!(ScoringSystem::from_str("BLOSUM_62").unwrap(), ScoringSystem::Blosum62);
        assert_eq!(ScoringSystem::from_str("blosum62").unwrap(), ScoringSystem::Blosum62);
        assert_eq!(ScoringSystem::from_str("PAM250").unwrap(), ScoringSystem::Pam250);
    }

    #[test]
    fn blosum62_diagonal_is_positive_off_diagonal_can_be_negative() {
        let m = ScoreMatrix::new(ScoringSystem::Blosum62);
        assert!(m.score(b'A', b'A') > 0);
        assert!(m.score(b'A', b'R') < 0);
        assert_eq!(m.score(b'W', b'W'), 11);
    }

    #[test]
    fn case_insensitive_lookup() {
        let m = ScoreMatrix::new(ScoringSystem::Blosum62);
        assert_eq!(m.score(b'a', b'A'), m.score(b'A', b'A'));
    }

    #[test]
    fn all_matrices_have_distinct_lambda() {
        let lambdas: Vec<f64> = [
            ScoringSystem::Blosum45,
            ScoringSystem::Blosum50,
            ScoringSystem::Blosum62,
            ScoringSystem::Blosum80,
            ScoringSystem::Blosum90,
            ScoringSystem::Pam30,
            ScoringSystem::Pam70,
            ScoringSystem::Pam250,
        ]
        .iter()
        .map(|s| ScoreMatrix::new(*s).karlin_altschul_params().0)
        .collect();
        // BLOSUM62 and BLOSUM80 should have different lambda
        assert_ne!(lambdas[2], lambdas[3]);
    }
}
